"""Generate src/lua/TWDRewindScenes.lua from the games' own developer scene tables.

Every Season 3/4 episode's Episode.lua registers a developer jump menu in Episode_Init:
    DebugMenu_AddButton(act, "Label", "SceneScript", "LogicSet( kAct, 2 ); ...")
Each scene script (e.g. BoardingSchoolBasement.lua) opens one scene file (adv_boardingSchoolBasement);
that scene name is what the game writes into the event log's "Start Scene" events.

Input: luadis.py listings of the episode archives, one folder per archive, named like
WDC_pc_WalkingDead401_data (as produced by the research scripts).
Usage: python -I gen_scene_table.py <dis_root> <out.lua>
"""
import sys, os, re

dis_root, out_path = sys.argv[1:3]
EPISODES = {3: range(301, 306), 4: range(401, 405)}
LOADK = re.compile(r"LOADK\s+R(\d+) := (?:'((?:[^'\\]|\\.)*)'|\"((?:[^\"\\]|\\.)*)\"|(-?[0-9.]+))")


def blocks(text):
    return re.split(r'(?m)^(?===== )', text)


def episode_buttons(path):
    text = open(path, encoding='utf-8', errors='replace').read()
    init = next(b for b in blocks(text) if b.startswith('==== Episode_Init '))
    buttons, regs = [], {}
    for line in init.splitlines():
        if "U0['DebugMenu_AddButton']" in line:
            regs = {}
            continue
        m = LOADK.search(line)
        if m:
            regs[int(m.group(1))] = m.group(2) if m.group(2) is not None else (m.group(3) if m.group(3) is not None else float(m.group(4)))
            continue
        m = re.search(r'CALL\s+R0\((\d+) args', line)
        if m and regs:
            args = [regs.get(i) for i in range(1, int(m.group(1)) + 1)]
            buttons.append(args)
            regs = {}
    return buttons


def scene_of(ep_dir, script):
    p = os.path.join(ep_dir, script + '.lua.txt')
    if not os.path.exists(p):
        return None
    text = open(p, encoding='utf-8', errors='replace').read()
    main = next((b for b in blocks(text) if b.startswith('==== <main>')), '')
    for m in LOADK.finditer(main):
        v = m.group(2)
        if v and re.match(r'^adv_\w+$', v):
            return v
    return None


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = ['-- Generated by tools/gen_scene_table.py from the games\' developer scene tables',
         '-- (Episode_Init in each episode\'s Episode.lua). Do not edit by hand.',
         '-- [season][episode] = list of { act, label, script, scene, command } in the order Telltale listed them.',
         'TWDRewindScenes = {']
for season, eps in EPISODES.items():
    lines.append('    [%d] = {' % season)
    for e in eps:
        ep_dir = os.path.join(dis_root, 'WDC_pc_WalkingDead%d_data' % e)
        path = os.path.join(ep_dir, 'Episode.lua.txt')
        lines.append('        [%d] = {' % (e % 100))
        kept = skipped = 0
        for args in episode_buttons(path):
            act = int(args[0]) if isinstance(args[0], float) else 1
            label = args[1] if len(args) > 1 else None
            script = args[2] if len(args) > 2 else None
            command = args[3] if len(args) > 3 and isinstance(args[3], str) else ''
            if not script or not isinstance(script, str) or script == 'Configurator':
                continue  # act headers and the choice configurator
            if 'Debug ID' in command:
                skipped += 1
                continue  # mid-scene developer variants; the log can't tell them apart
            scene = scene_of(ep_dir, script)
            if not scene:
                skipped += 1
                continue
            lines.append('            { act = %d, label = %s, script = %s, scene = %s, command = %s },' % (
                act, lua_str(label), lua_str(script), lua_str(scene), lua_str(command)))
            kept += 1
        lines.append('        },')
        print('%d: %d scene entries (%d skipped)' % (e, kept, skipped))
    lines.append('    },')
lines.append('}')
open(out_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', out_path)
